/* ── Search ───────────────────────────────────────────────────── */

/** Case-insensitive match of `query` against an entry's title/keywords/body. */
function entryMatches(entry: HelpEntry, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  const haystack = [
    entry.title,
    ...(entry.keywords ?? []),
    ...entry.body,
    ...(entry.bullets ?? []),
  ]
    .join(" ")
    .toLowerCase();
  return haystack.includes(q);
}

/**
 * Filter the help content by a search query. Sections with no matching entry
 * are dropped; an empty query returns everything (same structure, so callers
 * render one shape either way).
 */
export function searchHelp(query: string): HelpSection[] {
  if (!query.trim()) return HELP_SECTIONS;
  return HELP_SECTIONS.map((section) => ({
    ...section,
    entries: section.entries.filter((entry) => entryMatches(entry, query)),
  })).filter((section) => section.entries.length > 0);
}

/**
 * Help Center — the structured, searchable help content shared by ALL apps.
 *
 * Content lives in core (like `PRICING_GUIDE`) so web, desktop and mobile can
 * never drift (AGENTS §2/§4b): apps own only the rendering — web/desktop render
 * it through @munim/ui's `<HelpCenter />`, mobile renders it with RN primitives.
 *
 * Every page, every New Bill field, every filter, every bill-template toggle
 * and every report type gets one entry. `docs/pages.md` mirrors this content
 * for the repo docs.
 */

/** One help item — an accordion row with a deep-linkable id. */
export type HelpEntry = {
  /** Stable anchor (`#…`) used for deep links from other screens. */
  id: string;
  /** The question / field / page name — the searchable headline. */
  title: string;
  /** Extra search terms (synonyms, abbreviations, Hindi-ish phrasings). */
  keywords?: string[];
  /** Plain-text paragraphs, rendered in order. */
  body: string[];
  /** Optional bullet list shown after the paragraphs. */
  bullets?: string[];
};

/** A group of entries — rendered as one accordion/search group. */
export type HelpSection = {
  id: string;
  title: string;
  /** One-line description shown under the section title. */
  description?: string;
  entries: HelpEntry[];
};

